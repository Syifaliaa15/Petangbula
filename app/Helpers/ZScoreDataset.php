    // BB/U — Berat Badan menurut Umur (0-60 bulan)
    // ============================================================
    public static function getBBU(string $gender, int $umurBulan): ?array
    {
        $data = self::bbuData();
        $umurBulan = max(0, min(60, $umurBulan));
        return $data[$umurBulan][$gender] ?? null;
    }

    // ============================================================
    // TB/U — Panjang/Tinggi Badan menurut Umur (0-60 bulan)
    // Umur 0-23 → PB (Tabel 2/9)
    // Umur 24-60 → TB (Tabel 3/10)
    // ============================================================
    public static function getTBU(string $gender, int $umurBulan): ?array
    {
        $data = self::tbuData();
        $umurBulan = max(0, min(60, $umurBulan));
        return $data[$umurBulan][$gender] ?? null;
    }

    // ============================================================
    // BB/TB — Berat Badan menurut Panjang/Tinggi Badan
    // Umur < 24 bulan → pakai BB/PB (Tabel 4/11), key TB 45-110 cm
    // Umur >= 24 bulan → pakai BB/TB (Tabel 5/12), key TB 65-120 cm
    // ============================================================
    public static function getBBTB(string $gender, float $tb, int $umurBulan): ?array
    {
        if ($umurBulan < 24) {
            $data = self::bbpbData()[$gender] ?? [];
            $tbKey = (int) round($tb);
            $tbKey = max(45, min(110, $tbKey));
        } else {
            $data = self::bbtbData()[$gender] ?? [];
            $tbKey = (int) round($tb);
            $tbKey = max(65, min(120, $tbKey));
        }
        return $data[$tbKey] ?? null;
    }

